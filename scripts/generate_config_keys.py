#!/usr/bin/env python3
"""Generate src/libslic3r/ConfigKeys.hpp from PrintConfig.cpp key definitions.

Parses every literal key registration `this->add("key", ...)` in PrintConfig.cpp
(the single source of truth for config keys) and emits one
`constexpr const char*` per key into `namespace cfg` of ConfigKeys.hpp.

Usage:
  python scripts/generate_config_keys.py            # (re)generate the header
  python scripts/generate_config_keys.py --check    # verify header is in sync, exit 1 if not

The generated file is checked into the repo. CI re-runs this script with
--check so a key added/removed without regenerating fails the build.
Idempotency: running twice on the same source produces byte-identical output
(definition order preserved, no timestamps).
"""

import argparse
import re
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
DEFAULT_SOURCE = REPO_ROOT / "src" / "libslic3r" / "PrintConfig.cpp"
DEFAULT_OUTPUT = REPO_ROOT / "src" / "libslic3r" / "ConfigKeys.hpp"

# Matches both registration forms at the definition site:
#   this->add("key", ...)       (pre-adoption literal form)
#   this->add(cfg::key, ...)    (post-adoption constant form)
# Dynamic registrations (macro OPT_KEY, project_schema.config_key) match
# neither alternative and are excluded.
ADD_RE = re.compile(r'this->add\((cfg::[A-Za-z_][A-Za-z0-9_]*|"[^"]+")')


def _normalize(token: str) -> str:
    return token[5:] if token.startswith("cfg::") else token.strip('"')
IDENTIFIER_RE = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*$")

HEADER = """\
// AUTO-GENERATED FILE -- DO NOT EDIT.
// Generated by scripts/generate_config_keys.py from src/libslic3r/PrintConfig.cpp
// (PrintConfigDef key registrations, definition order preserved).
// Regenerate with: python scripts/generate_config_keys.py
#pragma once

namespace cfg {

"""


def extract_keys(source_text: str) -> list:
    """Extract unique config key names in first-definition order.

    Line comments are skipped: PrintConfig.cpp carries a few commented-out
    registrations (dead code) whose keys must not become constants.

    A few keys (retract_lift_above, scale, ...) are registered into multiple
    config defs (Print/Filament/Printer) and are expected duplicates; the key
    name is the shared contract so one constant per unique key is correct.
    """
    registrations = []
    for line in source_text.splitlines():
        if line.lstrip().startswith("//"):
            continue
        registrations.extend(_normalize(t) for t in ADD_RE.findall(line))
    bad = [k for k in registrations if not IDENTIFIER_RE.match(k)]
    if bad:
        raise SystemExit(
            "ERROR: keys not usable as C++ identifiers (rename them or extend "
            "the generator naming rule): %s" % ", ".join(sorted(set(bad)))
        )
    keys, seen = [], set()
    for k in registrations:
        if k not in seen:
            seen.add(k)
            keys.append(k)
    return keys


def render_header(keys: list) -> str:
    lines = [HEADER]
    for k in keys:
        lines.append('constexpr const char* %s = "%s";\n' % (k, k))
    lines.append("\n} // namespace cfg\n")
    return "".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--source", type=Path, default=DEFAULT_SOURCE,
                        help="PrintConfig.cpp path (default: %(default)s)")
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT,
                        help="ConfigKeys.hpp path (default: %(default)s)")
    parser.add_argument("--check", action="store_true",
                        help="verify the generated header is in sync; exit 1 if not")
    args = parser.parse_args()

    if not args.source.is_file():
        print("ERROR: source not found: %s" % args.source, file=sys.stderr)
        return 1

    keys = extract_keys(args.source.read_text(encoding="utf-8"))
    content = render_header(keys)

    if args.check:
        if not args.output.is_file():
            print("ERROR: %s is missing. Regenerate it with:"
                  % args.output, file=sys.stderr)
            print("  python scripts/generate_config_keys.py", file=sys.stderr)
            return 1
        current = args.output.read_bytes()
        if current != content.encode("utf-8"):
            print("ERROR: %s is out of sync with %s (%d keys)."
                  % (args.output, args.source.name, len(keys)), file=sys.stderr)
            print("Regenerate it and commit the result:", file=sys.stderr)
            print("  python scripts/generate_config_keys.py", file=sys.stderr)
            return 1
        print("OK: %s in sync (%d keys)." % (args.output, len(keys)))
        return 0

    with open(args.output, "w", encoding="utf-8", newline="\n") as f:
        f.write(content)
    print("Wrote %s (%d keys)." % (args.output, len(keys)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
